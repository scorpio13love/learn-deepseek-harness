/**
 * 离线 scripted model：不联网，按消息历史决定下一步工具调用。
 * 同一 fixture + 同一实现 => 稳定的事件日志与评测结果。
 */

import type {
  AssistantTurn,
  ChatMessage,
  JsonObject,
  JsonValue,
  Model,
  ModelRequest,
  ToolCall,
  Usage,
} from './types.ts'

interface SearchMatch {
  file: string
  line: number
  text: string
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function parseObject(message: ChatMessage | undefined): Record<string, unknown> | undefined {
  if (message === undefined) return undefined
  try {
    const parsed = JSON.parse(message.content) as unknown
    return isRecord(parsed) ? parsed : undefined
  } catch {
    return undefined
  }
}

function toolMessages(messages: readonly ChatMessage[], name: string): ChatMessage[] {
  return messages.filter(message => message.role === 'tool' && message.name === name)
}

function lastTool(messages: readonly ChatMessage[], name: string): ChatMessage | undefined {
  return toolMessages(messages, name).at(-1)
}

function usageFor(request: ModelRequest, turn: number): Usage {
  return {
    inputTokens: 120 + request.messages.length * 10,
    outputTokens: 30 + turn * 5,
  }
}

function call(id: string, name: string, args: JsonObject): ToolCall {
  return { id, name, arguments: args }
}

function buildReport(messages: readonly ChatMessage[]): { content: string; findings: SearchMatch[] } {
  const reads = new Map<string, string>()
  for (const message of toolMessages(messages, 'read_file')) {
    const output = parseObject(message)
    const path = typeof output?.path === 'string' ? output.path : undefined
    const content = typeof output?.content === 'string' ? output.content : undefined
    if (path !== undefined && content !== undefined) reads.set(path, content)
  }

  const search = parseObject(lastTool(messages, 'search_text'))
  const rawMatches = Array.isArray(search?.matches) ? search.matches : []
  const seen = new Set<string>()
  const findings: SearchMatch[] = []
  for (const raw of rawMatches) {
    if (!isRecord(raw)) continue
    const file = typeof raw.file === 'string' ? raw.file : undefined
    const line = typeof raw.line === 'number' ? raw.line : undefined
    const text = typeof raw.text === 'string' ? raw.text : undefined
    if (file === undefined || line === undefined || text === undefined) continue
    const key = `${file}:${line}:${text}`
    if (seen.has(key)) continue
    seen.add(key)
    findings.push({ file, line, text })
  }
  findings.sort((left, right) => left.file.localeCompare(right.file) || left.line - right.line)

  const files = [...reads.keys()].sort()
  const lines = [
    '# Repository audit',
    '',
    '## Summary',
    '',
    `Found ${findings.length} task markers across ${files.length} reviewed files.`,
    '',
    '## Findings',
    '',
    ...findings.map(finding => `- \`${finding.file}:${finding.line}\` — ${finding.text}`),
    '',
    '## Files reviewed',
    '',
    ...files.map(file => `- \`${file}\``),
    '',
    '## Notes',
    '',
    'Generated by the s28 capstone offline smoke model. Findings are file:line citations from search_text.',
    '',
  ]
  return { content: lines.join('\n'), findings }
}

export class OfflineModel implements Model {
  readonly provider = 'offline'
  readonly model = 'offline-scripted'
  #turn = 0

  async complete(request: ModelRequest): Promise<AssistantTurn> {
    this.#turn += 1
    const turn = this.#turn
    const usage = usageFor(request, turn)
    const messages = request.messages
    const used = new Set(messages.filter(message => message.role === 'tool').map(message => message.name))

    if (!used.has('list_files')) {
      const text = '先列出仓库文件。'
      return {
        text,
        toolCalls: [call(`call-list-${turn}`, 'list_files', {})],
        usage,
        finishReason: 'tool-calls',
      }
    }

    if (!used.has('read_file')) {
      const list = parseObject(lastTool(messages, 'list_files'))
      const files = Array.isArray(list?.files) ? list.files.filter((file): file is string => typeof file === 'string') : []
      const selected = files
        .filter(file => /\.(md|ts|js)$/.test(file) && !file.endsWith('audit.md'))
        .slice(0, 6)
      const targets = selected.length > 0 ? selected : ['README.md', 'src/app.ts', 'src/util.ts']
      return {
        text: `读取 ${targets.length} 个文件。`,
        toolCalls: targets.map((path, index) => call(`call-read-${turn}-${index}`, 'read_file', { path })),
        usage,
        finishReason: 'tool-calls',
      }
    }

    if (!used.has('search_text')) {
      return {
        text: '搜索 TODO / FIXME。',
        toolCalls: [call(`call-search-${turn}`, 'search_text', { query: 'TODO|FIXME', regex: true })],
        usage,
        finishReason: 'tool-calls',
      }
    }

    if (!used.has('write_file')) {
      const report = buildReport(messages)
      return {
        text: `写报告，共 ${report.findings.length} 条发现。`,
        toolCalls: [call(`call-write-${turn}`, 'write_file', { path: 'audit.md', content: report.content })],
        usage,
        finishReason: 'tool-calls',
      }
    }

    const report = buildReport(messages)
    const write = lastTool(messages, 'write_file')
    if (write?.isError === true) {
      const text = '写入 audit.md 被拒绝，因此没有交付报告。'
      return { text, toolCalls: [], usage, finishReason: 'stop' }
    }
    const text = `审计完成：写入了 audit.md，共 ${report.findings.length} 条 TODO/FIXME。`
    return { text, toolCalls: [], usage, finishReason: 'stop' }
  }
}

export { buildReport }
export type { SearchMatch }
